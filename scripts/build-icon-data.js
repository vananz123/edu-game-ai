// build-icon-data.js — generates src/renderer/features/icon-data.ts from the ONE
// authoritative registry, src/shared/icon-registry.ts (docs/DECISIONS.md #67).
//
// Why a copy exists at all: src/renderer/* is loaded as classic <script> tags
// by index.html, and src/shared/* compiles to CommonJS, so the renderer cannot
// import the registry. The preload cannot help either - it runs with
// `sandbox: true` and may only require('electron'), so requiring a local module
// there aborts the preload and silently removes `window.eduGame` entirely.
//
// The copy is therefore GENERATED at build time and verified, so it cannot
// drift by accident:
//   npm run build:icons           write the file
//   npm run build:icons:check     fail if the committed file is stale
//
// It reads the compiled registry (dist/) because this file is plain CommonJS run
// by node; every npm script that calls it compiles first
// (`build` -> tsc -> build:icons, `test` -> build).
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const TARGET = path.join(ROOT, 'src', 'renderer', 'features', 'icon-data.ts');
const REGISTRY = path.join(ROOT, 'dist', 'src', 'shared', 'icon-registry.js');

/* The generated file must exist BEFORE `tsc` runs, otherwise
 * game-illustration.ts cannot resolve `getIconNode`. On a clean checkout it may
 * be absent, so the build bootstraps a placeholder first and replaces it with
 * the real content after the registry has been compiled. */
function writePlaceholder() {
  fs.writeFileSync(
    TARGET,
    '// Placeholder; regenerated by scripts/build-icon-data.js.\n' +
      'const RENDERER_ICON_NODES: Readonly<Record<string, ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>>> = {};\n' +
      'function getIconNode(name: unknown): ReadonlyArray<readonly [string, Readonly<Record<string, string>>]> | null {\n  return typeof name === "string" && Object.prototype.hasOwnProperty.call(RENDERER_ICON_NODES, name) ? RENDERER_ICON_NODES[name] : null;\n}\n',
    'utf8'
  );
}

const HEADER = `// GENERATED FILE - DO NOT EDIT BY HAND.
// Produced from src/shared/icon-registry.ts by scripts/build-icon-data.js.
// Regenerate with: npm run build:icons
//
// The renderer is loaded as classic <script> tags and cannot import
// src/shared/* (CommonJS), and the sandboxed preload cannot require local
// modules (docs/DECISIONS.md #67). This file is the copy that makes item icons
// drawable on the play surface. \`npm run build\` regenerates it, and
// \`npm run build:icons:check\` fails if it is stale, so it cannot drift.
`;

const BODY = `const RENDERER_ICON_NODES = ${''}ICON_NODES_JSON as Readonly<Record<string, ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>>>;

/** Node array for an icon id, or null for anything unknown. Never throws. */
function getIconNode(name: unknown): ReadonlyArray<readonly [string, Readonly<Record<string, string>>]> | null {
  if (typeof name !== 'string' || !name) return null;
  return Object.prototype.hasOwnProperty.call(RENDERER_ICON_NODES, name) ? RENDERER_ICON_NODES[name] : null;
}
`;

function expectedContent() {
  if (!fs.existsSync(REGISTRY)) {
    console.error('FATAL: dist/src/shared/icon-registry.js is missing. Run `tsc -p tsconfig.json` first.');
    process.exit(1);
  }
  const { ICON_NODES } = require(REGISTRY);
  const json = JSON.stringify(ICON_NODES, null, 0);
  return {
    content: HEADER + '\n' + BODY.replace('ICON_NODES_JSON', json),
    count: Object.keys(ICON_NODES).length,
  };
}

const relative = path.relative(ROOT, TARGET);
const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--bootstrap') ? 'bootstrap' : 'write';

if (mode === 'bootstrap') {
  // Runs BEFORE tsc: only guarantee the file exists so the compiler can resolve
  // `getIconNode`. The real content is generated once the registry is compiled.
  if (!fs.existsSync(TARGET)) {
    writePlaceholder();
    console.log(`Created placeholder ${relative} (will be generated after tsc).`);
  }
} else {
  const { content, count } = expectedContent();
  if (mode === 'check') {
    const actual = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (actual !== content) {
      console.error(`FATAL: ${relative} is out of date with src/shared/icon-registry.ts.`);
      console.error('Run `npm run build:icons` and commit the result.');
      process.exit(1);
    }
    console.log(`${relative} is in sync (${count} icons).`);
  } else {
    fs.writeFileSync(TARGET, content, 'utf8');
    console.log(`Wrote ${relative} (${count} icons).`);
  }
}
